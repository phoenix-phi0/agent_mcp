"""按正则替换，返回替换后的文本；替换为 不给就是删掉匹配的部分。例如 替换 {作答} 。+$ 去掉末尾的句号

正则是 Python 的写法。参数按空格切，正则里要空格写 \\s；花括号会被当成
变量，量词写成 + * ? 或者把正则先「设」进变量。常用的几个：

    替换 {x} ^\\s+|\\s+$             去掉首尾空白（strip）
    替换 {x} 。+$                    去掉末尾的句号
    替换 {x} [\\u3040-\\u309f]+$      去掉末尾的一串平假名（送假名）
    替换 {x} ^\\s*\\[N[1-5]\\]\\s*      去掉开头的等级「[N4] 」

正则写错了直接抛：写错的正则悄悄当「没匹配上」，结果错了也看不出来。
"""

import re


def 替换(文本: str = "", 正则: str = "", 替换为: str = "") -> str:
    if not 正则:
        raise ValueError("替换：没给正则")
    try:
        return re.sub(正则, str(替换为 or ""), str(文本 or ""))
    except re.error as e:
        raise ValueError(f"替换：正则写错了（{e}）：{正则}")
